# Acessando um intervalo de elementos em uma lista
lista = [1, 2, 3, 4, 5]
print(lista[0:2])  # Saida [1,2,3]
print(lista[1:4])  # Saida [2,3,4]

# Acessando um intervalo de caracteres em uma string
frase = "Ola python!"
print(frase[0:2])  # Saida vai ser: Ola
print(frase[4:10])  # Saida vai ser: Python
