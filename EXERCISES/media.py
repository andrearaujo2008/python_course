# Programa que faz a soma de 3 numeros
# No final sai a media aritimetica deles

a = float(input("Type the first number: "))
b = float(input("Type the second number: "))
c = float(input("Type the third number: "))

result = a + b + c
avarage = result / 3

print(f"The avarage of three numbers will be {avarage:.2f} ")
