# Programa que vai somar a potencialização o primeiro numero por segundo numero

n1 = int(input("Digite o primeiro numero: "))  # Primeiro numero que vai digitar
n2 = int(input("Digite o segundo numero: "))  # Segundo numero vai ser a potenciação

resultado = n1 ** n2

print(f"O resultado da potencializacao sera {resultado}")  # Resultado da potenciação
