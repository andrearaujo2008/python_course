# This app will sum the double from three numbers

# Read the numbers from user
n1 = float(input("Type the first number: "))
n2 = float(input("Type the second number: "))
n3 = float(input("Type the third number: "))

# This sum from numbers double
sum = (n1 * 2) + (n2 * 2) + (n3 * 2)

# This is result
print(f"The result double from three numbers are: {sum:.2f}")
